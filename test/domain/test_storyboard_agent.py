class InMemoryShotRepo:
    def __init__(self):
        self.shots: dict[str, Shot] = {}
        self.revisions: dict[str, ShotRevision] = {}

    def add_shot(self, shot: Shot) -> Shot:
        self.shots[shot.shot_id] = shot
        return shot

    def add_revision(self, revision: ShotRevision) -> ShotRevision:
        self.revisions[revision.shot_revision_id] = revision
        return revision


class InMemoryStoryboardRepo:
    def __init__(self):
        self.snapshots: dict[str, StoryboardSnapshot] = {}

    def add_snapshot(self, snapshot: StoryboardSnapshot) -> StoryboardSnapshot:
        self.snapshots[snapshot.storyboard_snapshot_id] = snapshot
        return snapshot


def _make_sample_shot_dict(
    planner_ref="s1",
    local_order=1,
    narration="This is the narration explaining the beat concept clearly.",
    target_duration=10.0,
    visual_goal="Establish visual context",
    visual_type=VisualType.STOCK_VIDEO.value,
    scene_description="Wide shot of a modern laboratory",
    generation_prompt="Cinematic shot of modern research facility with glowing screens",
    camera_movement="Slow pan right",
    evidence_refs=None,
):
    return {
        "planner_ref": planner_ref,
        "local_order": local_order,
        "narration": narration,
        "target_duration": target_duration,
        "visual_goal": visual_goal,
        "visual_type": visual_type,
        "scene_description": scene_description,
        "generation_prompt": generation_prompt,
        "camera_movement": camera_movement,
        "evidence_refs": evidence_refs or [],
    }


def _make_sample_storyboard_json(beat_ref="beat-instance-1", shots=None):
    if shots is None:
        shots = [_make_sample_shot_dict()]
    return json.dumps({
        "beat_ref": beat_ref,
        "shots": shots,
    })


def _create_standard_beat(beat_type=BeatType.HOOK, target_duration=15.0):
    return ContentBeat(
        beat_id="beat-instance-1",
        beat_lineage_id="beat-lineage-1",
        beat_type=beat_type,
        order=1,
        intent="Hook the audience with an engaging hook",
        target_duration=target_duration,
        importance=0.9,
        evidence_refs=("ev1",) if beat_type == BeatType.KNOWLEDGE else (),
    )


# 1. One ContentBeat can produce one or more Shots
def test_one_content_beat_can_produce_multiple_shots():
    beat = _create_standard_beat(beat_type=BeatType.HOOK, target_duration=15.0)
    input_data = StoryboardPlanningInput(
        content_plan_revision_id="plan-rev-1",
        beat=beat,
        video_title="Quantum Physics",
    )
    shots_data = [
        _make_sample_shot_dict(
            planner_ref="s1",
            local_order=1,
            target_duration=7.5,
        ),
        _make_sample_shot_dict(
            planner_ref="s2",
            local_order=2,
            target_duration=7.5,
            visual_type=VisualType.DIAGRAM.value,
        ),
    ]
    agent = StoryboardAgent(llm_caller=lambda p: _make_sample_storyboard_json(shots=shots_data))
    result = agent.generate_shots_for_beat(input_data)

    assert isinstance(result, StoryboardExecutionResult)
    assert len(result.shots) == 2
    assert len(result.shot_revisions) == 2


# 2. Every generated Shot receives a system-owned shot_id
def test_every_generated_shot_receives_system_owned_shot_id():
    beat = _create_standard_beat(target_duration=10.0)
    input_data = StoryboardPlanningInput(
        content_plan_revision_id="plan-rev-1",
        beat=beat,
    )
    agent = StoryboardAgent(
        llm_caller=lambda p: _make_sample_storyboard_json(
            shots=[_make_sample_shot_dict(planner_ref="s_custom_ref_1")]
        )
    )
    result = agent.generate_shots_for_beat(input_data)

    assert len(result.shots) == 1
    shot = result.shots[0]

    # Valid UUID generated by system
    uuid.UUID(shot.shot_id)
    # The temporary planner_ref was NOT used as shot_id
    assert shot.shot_id != "s_custom_ref_1"


# 3. Every initial ShotRevision receives a system-owned revision ID
