# 9. Factual narration with unsupported evidence is rejected in source-grounded mode
def test_factual_narration_with_unsupported_evidence_rejected():
    knowledge_beat = ContentBeat(
        beat_id="k-beat-1",
        beat_lineage_id="k-lineage-1",
        beat_type=BeatType.KNOWLEDGE,
        order=1,
        intent="Explain empirical findings",
        target_duration=10.0,
        importance=1.0,
        evidence_refs=("ev_grounded_1",),
    )

    # Case A: KNOWLEDGE beat produces shots with no evidence citations
    shots_no_ev = [_make_sample_shot_dict(evidence_refs=[])]
    agent = StoryboardAgent(llm_caller=lambda p: _make_sample_storyboard_json(shots=shots_no_ev))
    with pytest.raises(InsufficientEvidenceError) as exc_info:
        agent.generate_shots_for_beat(
            StoryboardPlanningInput(
                content_plan_revision_id="p1",
                beat=knowledge_beat,
                source_grounded=True,
            )
        )
    assert "requires verified evidence citations" in str(exc_info.value)

    # Case B: Shot cites an evidence ID not present in available_evidence_ids
    shots_unallowed_ev = [_make_sample_shot_dict(evidence_refs=["hallucinated_paper_99"])]
    agent2 = StoryboardAgent(
        llm_caller=lambda p: _make_sample_storyboard_json(shots=shots_unallowed_ev)
    )
    with pytest.raises(UnsupportedEvidenceReferenceError) as exc_info2:
        agent2.generate_shots_for_beat(
            StoryboardPlanningInput(
                content_plan_revision_id="p1",
                beat=knowledge_beat,
                available_evidence_ids=("ev_grounded_1",),
                source_grounded=True,
            )
        )
    assert "hallucinated_paper_99" in str(exc_info2.value)


# 10. Planned Shot duration must stay within the Beat-level tolerance
def test_planned_shot_duration_must_stay_within_tolerance():
    beat = _create_standard_beat(target_duration=20.0)

    # 20.0s target, 0.20 tolerance -> max deviation 4.0s (16.0s - 24.0s allowed)
    # Proposing 5.0s total -> invalid
    shots_too_short = [_make_sample_shot_dict(target_duration=5.0)]
    agent_short = StoryboardAgent(
        llm_caller=lambda p: _make_sample_storyboard_json(shots=shots_too_short)
    )
    with pytest.raises(InvalidShotDurationError) as exc_info:
        agent_short.generate_shots_for_beat(
            StoryboardPlanningInput(content_plan_revision_id="p1", beat=beat)
        )
    assert "deviates from beat target" in str(exc_info.value)

    # Proposing 35.0s total -> invalid
    shots_too_long = [_make_sample_shot_dict(target_duration=35.0)]
    agent_long = StoryboardAgent(
        llm_caller=lambda p: _make_sample_storyboard_json(shots=shots_too_long)
    )
    with pytest.raises(InvalidShotDurationError):
        agent_long.generate_shots_for_beat(
            StoryboardPlanningInput(content_plan_revision_id="p1", beat=beat)
        )


# 11. Excessive Shot count is rejected
def test_excessive_shot_count_is_rejected():
    beat = _create_standard_beat(target_duration=35.0)
    # Default limit is 6 shots per beat, propose 7
    shots_7 = [
        _make_sample_shot_dict(planner_ref=f"s{i}", local_order=i, target_duration=5.0)
        for i in range(1, 8)
    ]
    agent = StoryboardAgent(
        llm_caller=lambda p: _make_sample_storyboard_json(shots=shots_7),
        max_shots_per_beat=6,
    )

    with pytest.raises(ShotLimitExceededError) as exc_info:
        agent.generate_shots_for_beat(
            StoryboardPlanningInput(content_plan_revision_id="p1", beat=beat)
        )
    assert "exceeds maximum allowed shots per beat (6)" in str(exc_info.value)


# 12. Storyboard retry is bounded
def test_storyboard_retry_is_bounded():
    beat = _create_standard_beat(target_duration=10.0)
    input_data = StoryboardPlanningInput(content_plan_revision_id="p1", beat=beat)

    # Scenario A: Initial call returns broken JSON, second attempt repairs and succeeds
    call_count = 0
    prompts = []

    def healing_llm(prompt: str) -> str:
        nonlocal call_count
        call_count += 1
        prompts.append(prompt)
        if call_count == 1:
            return "broken json"
        return _make_sample_storyboard_json()

    agent_heal = StoryboardAgent(llm_caller=healing_llm, max_retries=2)
    result = agent_heal.generate_shots_for_beat(input_data)
    assert len(result.shots) == 1
    assert call_count == 2
    assert "[Correction Notice]" in prompts[1]

    # Scenario B: Always fails, terminates boundedly after max_retries + 1
    fail_count = 0

    def always_fail_llm(prompt: str) -> str:
        nonlocal fail_count
        fail_count += 1
        return "unfixable json"

    agent_fail = StoryboardAgent(llm_caller=always_fail_llm, max_retries=2)
    with pytest.raises(StoryboardOutputSchemaError):
        agent_fail.generate_shots_for_beat(input_data)
    assert fail_count == 3


