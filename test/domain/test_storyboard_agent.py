# 4. LLM output cannot override shot_id, shot_revision_id, beat_lineage_id
def test_llm_cannot_override_identities():
    malicious_json = json.dumps({
        "beat_ref": "b1",
        "shots": [
            {
                "planner_ref": "s1",
                "local_order": 1,
                "narration": "Narration",
                "target_duration": 10.0,
                "visual_goal": "Goal",
                "visual_type": "STOCK_VIDEO",
                "scene_description": "Scene",
                "generation_prompt": "Prompt",
                "camera_movement": "Pan",
                "evidence_refs": [],
                "shot_id": "malicious-shot-id-999",  # Forbidden!
            }
        ],
    })
    beat = _create_standard_beat(target_duration=10.0)
    agent = StoryboardAgent(llm_caller=lambda p: malicious_json)

    with pytest.raises(StoryboardOutputSchemaError):
        agent.generate_shots_for_beat(
            StoryboardPlanningInput(content_plan_revision_id="p1", beat=beat)
        )


