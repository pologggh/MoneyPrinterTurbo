# 14. If a StoryboardSnapshot is created, it contains exact ShotRevision IDs
def test_storyboard_snapshot_contains_exact_shot_revision_ids():
    beat = _create_standard_beat(target_duration=10.0)
    agent = StoryboardAgent(llm_caller=lambda p: _make_sample_storyboard_json())
    result = agent.generate_shots_for_beat(
        StoryboardPlanningInput(content_plan_revision_id="plan-rev-10", beat=beat)
    )

    snapshot_repo = InMemoryStoryboardRepo()
    snapshot = agent.create_draft_snapshot(
        content_plan_revision_id="plan-rev-10",
        shot_revisions=result.shot_revisions,
        storyboard_repository=snapshot_repo,
    )

    assert isinstance(snapshot, StoryboardSnapshot)
    assert snapshot.snapshot_state == StoryboardSnapshotState.DRAFT
    assert snapshot.content_plan_revision_id == "plan-rev-10"
    assert snapshot.shot_revision_ids == (result.shot_revisions[0].shot_revision_id,)
    # Persisted into repo
    assert snapshot.storyboard_snapshot_id in snapshot_repo.snapshots


# Extra: Persistence integration with ShotRepository
def test_shots_persist_through_repository():
    beat = _create_standard_beat(target_duration=10.0)
    shot_repo = InMemoryShotRepo()

    agent = StoryboardAgent(
        shot_repository=shot_repo,
        llm_caller=lambda p: _make_sample_storyboard_json(),
    )
    result = agent.generate_shots_for_beat(
        StoryboardPlanningInput(content_plan_revision_id="plan-rev-10", beat=beat)
    )

    assert len(shot_repo.shots) == 1
    assert len(shot_repo.revisions) == 1
    assert result.shots[0].shot_id in shot_repo.shots
    assert result.shot_revisions[0].shot_revision_id in shot_repo.revisions
